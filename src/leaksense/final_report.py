"""``reports/FINAL.md`` from ``final.json`` (M13). Every number here is read from the report."""

from __future__ import annotations

H5_BIG_TRIVIAL = 0.95  # "close to trivial": big-leak top-3 >= 95% at every k >= the headline k


def _p(d, pct=True) -> str:
    if not d:
        return "-"
    f = (lambda x: f"{100 * x:.1f}") if pct else (lambda x: f"{x:.0f}")
    return f"{f(d['value'])} [{f(d['lo'])}, {f(d['hi'])}]"


def _v(d) -> str:
    return "-" if not d else f"{100 * d['value']:.1f}"


def _d(d) -> str:
    return f"{100 * d['value']:+.1f} [{100 * d['lo']:+.1f}, {100 * d['hi']:+.1f}]"


def _ks(xs) -> str:
    return ", ".join(str(x) for x in xs) if xs else "none"


def render_markdown(rep: dict) -> str:
    prov, res, ks = rep["provenance"], rep["results"], rep["ks"]
    hk, fk = str(rep["headline_k"]), str(rep["full_k"])
    head, ts = rep["headline"], rep["test_set"]
    g = prov["git"]
    test = rep["mode"] == "test"
    where = "locked test" if test else f"stand-in fold {rep['mode'].split('_f')[-1]}"
    L = [f"# LeakSense: final report ({where})", ""]
    if not test:
        L += [
            f"> **Stand-in run.** CV fold {rep['mode'].split('_f')[-1]} plays the test set and "
            "the models train on the other folds. This is a pipeline and timing check, not the "
            "locked test. The final placement was chosen with this fold's cases, so its numbers "
            "are optimistic here.",
            "",
        ]
    if rep["units_missing"]:
        L += [f"> **Incomplete:** units not run: {', '.join(rep['units_missing'])}.", ""]
    L += [
        f"- **Generated by:** `{rep['command']}`, config `{prov['config'].get('name')}`, commit "
        f"`{(g['commit'] or '?')[:10]}`{' (dirty)' if g['dirty'] else ''}, data manifest "
        f"`{(prov['data_manifest_sha256'] or '?')[:12]}`, features "
        f"`{rep['fingerprint']['features_dir']}` (`{rep['fingerprint']['features_sha256_12']}`), "
        f"splits sha `{rep['fingerprint']['splits_sha256'][:12]}`, seed {prov['seed']}.",
        f"- **Training:** every rung is fit once on {rep['n_train_cases']} CV cases (inner "
        "validation split for early stopping and grids, then a refit, as in CV). Training seeds: "
        + "; ".join(
            f"{r} {','.join(str(s) for s in rr['seeds'])}"
            for r, rr in res.items()
            if any(s is not None for s in rr["seeds"])
        )
        + ". With several seeds, per-case metrics are averaged over them.",
        f"- **{where.capitalize()} set:** {ts['n_cases']} cases from {ts['n_scenarios']} "
        f"scenarios; leak type {ts['leak_type']}; kind {ts['kind']}; baseline {ts['baseline_kind']}"
        ". Median leak flow (L/s): "
        + ", ".join(f"{t} {v:.0f}" for t, v in ts["leak_flow_lps_median"].items())
        + ".",
        f"- **Sensor sets:** k < {rep['full_k']} averages each case over the same {rep['draws']} "
        "seeded random "
        "sets per k as every CV report. The placement section uses the M11 final placement.",
        "- **Metrics:** tie-aware top-k; hop and network distance (m) from the top-1 pipe's "
        f"midpoint to the true leak point. 95% CIs: {rep['bootstrap']} bootstrap resamples over "
        "scenarios; paired differences are per case on the same cases.",
        "- **Groups:** leak-flow and SNR terciles use the CV edges (leak flow "
        + ", ".join(f"{e:.1f}" for e in rep["tercile_edges"]["leak_flow_lps"])
        + " L/s; SNR "
        + ", ".join(f"{e:.1f}" for e in rep["tercile_edges"]["snr"])
        + "), so test and CV groups match.",
        "",
    ]
    dn = rep.get("data_notes", {})
    if dn:
        L += ["## Data and pipeline (M3, M4)", ""]
        c = dn.get("cases")
        if c:
            cc = c.get("config") or {}
            base_d = cc.get("min_baseline_steps", 0) / 48
            solo_d = cc.get("min_solo_steps", 0) / 48
            L.append(
                f"- **Cases (M3):** {c['cases']['total']} cases ({c['cases']['pure']} pure, "
                f"{c['cases']['solo']} solo) from {c['candidates']['total']} candidates; "
                f"{c['n_excluded']} excluded for lack of a {base_d:.0f}-day leak-free baseline. "
                f"Two-leak scenarios whose first leak runs alone for under {solo_d:.0f} days give "
                f"no case ({c['n_two_leak_without_solo']})."
            )
        b = dn.get("baseline")
        if b:
            meth = ", ".join(f"{k}: `{v}`" for k, v in b["method_by_stratum"].items())
            L.append(
                f"- **Baseline (M4):** {meth}; windows of {b['window']} steps, stride "
                f"{b['stride']}, at most {b['max_lag_days']:.0f} days from the baseline."
            )
        L.append("")

    # headline
    h = res.get(head, {}).get(hk, {})
    cvh = rep["cv"]["top3"].get(head, {})
    sig = res.get("sigmatch_all", {}).get(hk, {})
    if h:
        L += [
            "## Headline",
            "",
            f"Small-leak top-3 at k = {hk} (SPEC H5), `{head}`: "
            f"**{_p(h.get('leak_type=small', {}).get('top3'))}"
            f"** on the {where} (CV {_v(cvh.get('k_head_small'))}); `sigmatch_all` "
            f"{_p(sig.get('leak_type=small', {}).get('top3'))}. All cases: "
            f"{_p(h['overall']['top3'])} (CV {_v(cvh.get('k_head'))}).",
            "",
        ]

    for gname, title in (("overall", "all cases"), ("leak_type=small", "small leaks")):
        L += [
            f"## Ladder, top-3 (%), {title}, random sensor sets",
            "",
            "| rung | seeds | " + " | ".join(f"k={k}" for k in ks) + " |",
            "|---|---|" + "---|" * len(ks),
        ]
        for r, rr in res.items():
            seeds = ",".join(str(s) for s in rr["seeds"] if s is not None) or "-"
            cells = [_p(rr[str(k)].get(gname, {}).get("top3")) for k in ks]
            name = f"**{r}**" if r == head else r
            L.append(f"| {name} | {seeds} | " + " | ".join(cells) + " |")
        L.append("")

    L += [
        f"## CV vs {where}, top-3 (%)",
        "",
        "CV: pooled out-of-fold, from the CV reports (GAT variants from `ablation.json`, "
        "averaged over their seeds there).",
        "",
        f"| rung | CV k={hk} | {where} k={hk} | CV small k={hk} | {where} small k={hk} | "
        f"CV k={fk} | {where} k={fk} |",
        "|---|---|---|---|---|---|---|",
    ]
    for r, rr in res.items():
        c = rep["cv"]["top3"].get(r, {})
        L.append(
            f"| {r} | {_v(c.get('k_head'))} | {_v(rr[hk]['overall']['top3'])} | "
            f"{_v(c.get('k_head_small'))} | {_v(rr[hk].get('leak_type=small', {}).get('top3'))} | "
            f"{_v(c.get('k_full'))} | {_v(rr[fk]['overall']['top3'])} |"
        )
    L.append("")

    if head in res:
        for k in dict.fromkeys((int(hk), int(fk))):
            L += [
                f"## `{head}` by group, k = {k}",
                "",
                "| group | n | top-1 | top-3 | top-5 | hop mean | dist median (m) |",
                "|---|---|---|---|---|---|---|",
            ]
            for gname, d in res[head][str(k)].items():
                L.append(
                    f"| {gname} | {d['n']} | {_p(d['top1'])} | {_p(d['top3'])} | "
                    f"{_p(d['top5'])} | {d['hop_mean']['value']:.2f} | "
                    f"{_p(d['dist_m_median'], False)} |"
                )
            L.append("")
        show = [k for k in (4, 8, 16, 31) if k in ks] or list(ks)
        L += [
            f"## `{head}` minus each rung, top-3 (points, paired)",
            "",
            "| rung | " + " | ".join(f"k={k}" for k in show) + f" | small, k={hk} |",
            "|---|" + "---|" * (len(show) + 1),
        ]
        for r, d in rep["headline_minus"].items():
            cells = [_d(d[str(k)]["overall"]["top3"]) for k in show]
            sm = d[hk].get("leak_type=small")
            L.append(f"| {r} | " + " | ".join(cells) + f" | {_d(sm['top3']) if sm else '-'} |")
        L.append("")

    L += hypotheses_md(rep, where)
    L += placement_md(rep, where)

    fl = rep.get("leak_flow_curve") or {}
    if fl.get("series"):
        L += [
            "## Accuracy vs leak flow (H5)",
            "",
            "![top-3 vs leak flow](final_leak_flow.png)",
            "",
            f"Top-3 (%) at k = {fl['k']}, random sets, by leak-flow bin (bins are CV sextiles). "
            "Leak flow is used for reporting only.",
            "",
            "| bin (L/s) | " + " | ".join(fl["series"]) + " |",
            "|---|" + "---|" * len(fl["series"]),
        ]
        first = next(iter(fl["series"].values()))
        for i, b in enumerate(first):
            hi = "inf" if b["hi"] == float("inf") else f"{b['hi']:.0f}"
            cells = []
            for rows in fl["series"].values():
                r = rows[i]
                cells.append("-" if r["top3"] is None else f"{100 * r['top3']:.1f} (n={r['n']})")
            L.append(f"| {b['lo']:.0f}–{hi} | " + " | ".join(cells) + " |")
        L.append("")

    L += notes_md(rep, where)
    L += [
        "## Units",
        "",
        "| unit | seconds |",
        "|---|---|",
        *[f"| {n} | {s:.0f} |" for n, s in rep["unit_seconds"].items() if s is not None],
        "",
        f"Report built in {rep['elapsed_seconds']:.0f} s.",
        "",
    ]
    return "\n".join(L)


def hypotheses_md(rep: dict, where: str) -> list[str]:
    hyp, cvh, res, head = (
        rep["hypotheses"],
        rep["cv"]["hypotheses"],
        rep["results"],
        rep["headline"],
    )
    L = ["## Hypotheses (SPEC section 6)", ""]
    hk = rep["headline_k"]
    h2_ks = [k for k in rep["ks"] if k <= 6]

    # H1
    L += [
        f"### H1: at k ≥ {hk} the GAT beats the best non-learned rung on top-3, CIs not "
        "overlapping",
        "",
        f"| variant | k | vs | GAT top-3 | best non-learned | paired diff | {where} |",
        "|---|---|---|---|---|---|---|",
    ]
    for v, per_k in hyp["H1"].items():
        if not v.startswith("gat"):
            continue
        for k, d in per_k.items():
            verdict = "holds" if d["holds"] else "worse" if d["worse"] else "CIs overlap"
            L.append(
                f"| {v} | {k} | {d['vs']} | {_p(res[v][k]['overall']['top3'])} | "
                f"{_p(res[d['vs']][k]['overall']['top3'])} | {_d(d['paired']['top3'])} | "
                f"{verdict} |"
            )
    h1_head = hyp["H1"].get(head, {})
    held = [k for k, d in h1_head.items() if d["holds"]]
    cv1 = cvh.get("H1", {}).get(head, {})
    cv_held = [k for k, d in cv1.items() if d.get("holds")]
    L += [
        "",
        f"**`{head}`: holds at k = {_ks(held)} on the {where}** (CV: holds at k = {_ks(cv_held)}).",
        "",
    ]

    # H2
    L += [
        "### H2: at k ≤ 6, physics inputs improve on the plain GAT",
        "",
        f"Paired top-3 difference vs `{rep['plain']}` (points).",
        "",
        "| variant | " + " | ".join(f"k={k}" for k in h2_ks) + f" | {where} | CV |",
        "|---|" + "---|" * (len(h2_ks) + 2),
    ]
    for v, d in hyp["H2"].items():
        cells = [_d(d["per_k"][str(k)]["diff"]) if str(k) in d["per_k"] else "-" for k in h2_ks]
        cv = cvh.get("H2", {}).get(v, {}).get("holds", "-")
        L.append(f"| {v} | " + " | ".join(cells) + f" | {d['holds']} | {cv} |")
    L.append("")

    # H3
    h3 = hyp.get("H3")
    if h3:
        cv3 = cvh.get("H3", {})
        L += [
            "### H3: greedy beats the random median at every k from 2 to 16, and the random p95 "
            "for k ≤ 8",
            "",
            f"| k | beats median ({where}) | above p95 ({where}) | beats median (CV) | "
            "above p95 (CV) |",
            "|---|---|---|---|---|",
        ]

        def yn(x):
            return "-" if x is None else "yes" if x else "no"

        for k, d in h3["per_k"].items():
            c = cv3.get("per_k", {}).get(k, {})
            L.append(
                f"| {k} | {yn(d['beats_median'])} | {yn(d['above_p95'])} | "
                f"{yn(c.get('beats_median'))} | {yn(c.get('above_p95'))} |"
            )
        L += ["", f"**H3: {h3['holds']} on the {where}** (CV: {cv3.get('holds', '-')}).", ""]

    # H4
    h4 = hyp.get("H4") or {}
    if h4.get("per_k"):
        cv4 = cvh.get("H4", {})
        L += [
            "### H4: the one masked model is within 3 points of top-3 of a model trained for one "
            f"fixed sensor set (k = {', '.join(h4['per_k'])})",
            "",
            "Fixed set = the final greedy set at k. Masked = the headline model (seed 0) on the "
            "same set.",
            "",
            f"| k | fixed top-3 | masked top-3 | masked − fixed ({where}) | masked − fixed (CV) |",
            "|---|---|---|---|---|",
        ]
        for k, d in h4["per_k"].items():
            o = d["overall"]
            c = cv4.get("per_k", {}).get(k, {}).get("overall", {}).get("masked_minus_fixed")
            L.append(
                f"| {k} | {_p(o['fixed']['top3'])} | {_p(o['masked']['top3'])} | "
                f"{_d(o['masked_minus_fixed']['top3'])} | {_d(c['top3']) if c else '-'} |"
            )
        L += [
            "",
            f"**H4: {h4['holds']} on the {where}** (CV: {cv4.get('holds', 'not run')}). Rule: "
            "masked − fixed ≥ −3 points (point estimate).",
            "",
        ]

    # H5
    h5 = hyp.get("H5")
    if h5:
        big = {k: d.get("leak_type=big") for k, d in h5.items() if int(k) >= hk}
        ok = all(d and d["value"] >= H5_BIG_TRIVIAL for d in big.values())
        L += [
            f"### H5: big leaks are close to trivial at k ≥ {hk}; the headline is small-leak "
            f"top-3 at k = {hk}",
            "",
            "| k | big top-3 | small top-3 | all top-3 |",
            "|---|---|---|---|",
        ]
        for k, d in h5.items():
            L.append(
                f"| {k} | {_p(d.get('leak_type=big'))} | {_p(d.get('leak_type=small'))} | "
                f"{_p(d.get('overall'))} |"
            )
        L += [
            "",
            f'**H5 (big-leak part): {"yes" if ok else "no"} on the {where}**, reading "close to '
            f'trivial" as big-leak top-3 ≥ {100 * H5_BIG_TRIVIAL:.0f}% at every k ≥ {hk}. The '
            "leak-flow plot below shows where the remaining errors are.",
            "",
        ]
    return L


def placement_md(rep: dict, where: str) -> list[str]:
    pl = rep["placement"]
    if not pl.get("results"):
        return []
    L = [
        f"## Sensor placement on the {where}",
        "",
        f"Final placement (M11, all CV cases), order: {', '.join(pl['final_order'])}. Coverage "
        f"order: {', '.join(pl['coverage_order'])}. Random: the same {pl['n_random']} sets as "
        "M11.",
        "",
        "![placement curve](final_placement_curve.png)",
        "",
    ]
    for scorer, title in ((rep["headline"], "model"), ("sigmatch_all", "sigmatch_all")):
        for g, gt in (("overall", "all cases"), ("leak_type=small", "small leaks")):
            L += [
                f"### Top-3 (%), {scorer}, {gt}",
                "",
                "| k | greedy | coverage | random mean | random p5–p95 | greedy pct | "
                "greedy − random | greedy − coverage |",
                "|---|---|---|---|---|---|---|---|",
            ]
            for k in pl["ks"]:
                r = pl["results"][title][str(k)].get(g)
                if not r:
                    continue
                dr = r["random_top3_draws"]
                L.append(
                    f"| {k} | {_p(r['greedy']['top3'])} | {_p(r['coverage']['top3'])} | "
                    f"{_p(r['random_mean']['top3'])} | {100 * dr['p5']:.1f}–{100 * dr['p95']:.1f}"
                    f" | {100 * r['greedy_percentile']:.0f} | "
                    f"{_d(r['greedy_minus_random']['top3'])} | "
                    f"{_d(r['greedy_minus_coverage']['top3'])} |"
                )
            L.append("")
    hk = str(rep["headline_k"])
    m = pl["results"]["model"].get(hk, {}).get("overall")
    s = pl["results"]["sigmatch_all"].get(hk, {}).get("overall")
    if m and s:
        L += [
            f"**Placement-matched comparison, k = {hk}, all cases:** "
            f"`{rep['headline']}` greedy {_v(m['greedy']['top3'])}, coverage "
            f"{_v(m['coverage']['top3'])}, random mean {_v(m['random_mean']['top3'])}; "
            f"`sigmatch_all` greedy {_v(s['greedy']['top3'])}, coverage "
            f"{_v(s['coverage']['top3'])}, random mean {_v(s['random_mean']['top3'])}.",
            "",
        ]
    return L


def placement_limits(rep: dict) -> list[str]:
    cp = rep["cv"].get("placement") or {}
    st = cp.get("stability", {}).get("8")
    if not st:
        return []
    txt = (
        f"- **Placement is unstable across folds** (M11: mean pairwise Jaccard "
        f"{st['jaccard']:.2f} at k = 8 vs {st['random_jaccard']:.2f} for random sets). The "
        f"greedy chose each step on {min(cp['fold_greedy_cases'])}–"
        f"{max(cp['fold_greedy_cases'])} inner cases per fold"
    )
    if "final_greedy_cases" in cp:
        txt += (
            f" ({cp['final_greedy_cases']} for the final set, whose inner top-3 reaches its "
            f"maximum of {100 * cp['final_max_inner_top3']:.1f}% at k = "
            f"{cp['final_saturates_at_k']}; larger sets past that point are set by the "
            "tie-break)"
        )
    return [txt + "."]


def post_hoc_md(rep: dict, where: str) -> list[str]:
    rule = rep.get("rule_pick")
    if not rule or rule == rep["headline"]:
        return []
    both = rule in rep["results"] and rep["headline"] in rep["results"]
    return [
        f"- **The headline model `{rep['headline']}` was picked post hoc on CV** (PLAN.md M10). "
        f"The pre-registered stage-2 rule would have taken `{rule}`."
        + (f" Both are on the {where} above, so the choice can be checked." if both else "")
    ]


def notes_md(rep: dict, where: str) -> list[str]:
    ts = rep["test_set"]
    n_post = sum(v for k, v in ts["baseline_kind"].items() if k != "pre")
    return [
        "## Choices made after seeing CV results",
        "",
        *post_hoc_md(rep, where),
        "- **M12 (Kaggle) was skipped:** every run fit on the laptop CPU.",
        "- **H4 was run late** (CV in `reports/fixed_budget.md`, then here); no milestone had "
        "built the fixed-set model.",
        "",
        "## Limitations",
        "",
        f"- **Small test set:** {ts['n_cases']} cases from {ts['n_scenarios']} scenarios, so CIs "
        "are wide. Averaging over the per-k random sets reduces sensor-set luck but not case "
        "luck.",
        "- **Simulated data, one network:** LeakDB Hanoi only. Real sensor noise, drift, "
        "missing data and model error in the hydraulic network are not covered.",
        "- **The leak is known to be there:** localisation starts after detection (SPEC section "
        "1), and each case's windows come from the labelled leak period. Detection is a stretch "
        "goal (M15).",
        f"- **Post-leak baselines:** {n_post} of the {ts['n_cases']} cases use a baseline that "
        "includes data from after the leak, which an operator would not have in real time; the "
        "`pre_baseline_only` group shows the rest.",
        "- **Physics inputs use the nominal network:** each scenario's pipes differ by up to "
        "±20%, and S is computed once on the nominal `.inp`.",
        *placement_limits(rep),
        "- **Seeds:** the placement and H4 comparisons use the headline model at seed 0; ladder "
        "seeds per rung are listed at the top.",
        "- **Smallest leaks:** the smallest leaks (a few L/s) are probably below what pressure "
        "sensors can see (SPEC H5); the leak-flow table shows accuracy per flow bin.",
        "",
    ]
